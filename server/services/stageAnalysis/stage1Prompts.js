const DEFAULT_VARIANT = 'structural';

// Нормализует env STAGE1_PROMPT_VARIANT → один из ключей VARIANTS.
// Пусто/неизвестное → structural.
function resolveVariant() {
  const raw = (process.env.STAGE1_PROMPT_VARIANT || '').trim().toLowerCase();
  return Object.prototype.hasOwnProperty.call(VARIANTS, raw)
    ? raw
    : DEFAULT_VARIANT;
}

// Собирает системный промт: общий блок + блок выбранного режима.
function buildSystemPrompt(variant) {
  const v = Object.prototype.hasOwnProperty.call(VARIANTS, variant)
    ? variant
    : DEFAULT_VARIANT;
  return `${SHARED}\n\n${VARIANTS[v]}`;
}

module.exports = { buildSystemPrompt, resolveVariant, DEFAULT_VARIANT };
