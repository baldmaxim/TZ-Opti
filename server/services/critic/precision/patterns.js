'use strict';

// Текстовые признаки, по которым замечание распознаётся как НЕ подлежащее
// публикации. Вынесены отдельно, потому что ими пользуются два слоя —
// criticService (флаги подавления в модели материальности) и precision-критик
// (жёсткие фильтры). Модуль ни от чего не зависит: цикла require нет.
//
// Граница слова на кириллице: `\b` в JS опирается на ASCII-класс \w, поэтому на
// русском тексте не работает (см. LB/RB в criticService).

// Редактура: замечание про оформление текста, а не про деньги/сроки/обязательства.
const EDITORIAL_RE =
  /опечатк|орфограф|пунктуац|грамматич|стилистич|редакционн|нумерац|шрифт|форматирован|оформлени\w*\s+(текст|документ|таблиц)/;

// Стандартное требование: нормативы и обычная практика, которые ГП исполняет и так.
const STANDARD_REQUIREMENT_RE =
  /в соответствии с\s+(снип|гост|сп\b|сн\b|нормативн)|согласно\s+(снип|гост|нормативн)|требовани\w*\s+нормативн|стандартн\w*\s+требовани|обычн\w*\s+практик/;

// Язык предположения: замечание сформулировано как догадка, а не как факт из ТЗ.
// «Возможно», «вероятно», «не исключено», «может потребоваться», «скорее всего».
const ASSUMPTION_RE =
  /возможно|вероятн|предположительно|предполага|не исключено|скорее всего|по-видимому|повидимому|может (?:потребова|привести|возникнуть)|могут (?:потребова|возникнуть)/;

// Замечание-констатация без вывода: «информация приведена», «указано», «описано».
// Само по себе не скрывает — работает вместе с отсутствием последствия.
const INFORMATIONAL_RE =
  /для сведени|информационн|справочно|обратить внимание|принять к сведению/;

module.exports = {
  EDITORIAL_RE,
  STANDARD_REQUIREMENT_RE,
  ASSUMPTION_RE,
  INFORMATIONAL_RE,
};
